import { chromium } from '@playwright/test'
const base = process.env.BASE_URL ?? 'http://localhost:5174'
const out = process.argv[2]
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message))
page.on('console', (m) => {
  if (m.type() === 'error') errors.push('console: ' + m.text().slice(0, 200))
})
await page.goto(base + '/login', { waitUntil: 'networkidle' })
await page.getByRole('textbox', { name: 'Email', exact: true }).fill('admin@demo.local')
await page.getByRole('textbox', { name: /^password/i }).fill('password')
await page.getByRole('button', { name: /sign in/i }).click()
await page.waitForURL(/admin/)
await page.goto(base + '/admin/content', { waitUntil: 'networkidle' })
await page.waitForTimeout(800)
await page.screenshot({ path: `${out}/cms-1-content.png`, fullPage: true })
await page.goto(base + '/admin/editor?doc=page:home', { waitUntil: 'networkidle' })
await page.waitForTimeout(2500)
await page.screenshot({ path: `${out}/cms-2-editor.png` })
// select hero row
await page
  .getByRole('button', { name: /^Hero Everyday/ })
  .first()
  .click()
await page.waitForTimeout(500)
const title = page.getByLabel('Headline').first()
await title.fill('Edited by the CMS editor.')
await page.waitForTimeout(800)
await page.screenshot({ path: `${out}/cms-3-edited.png` })
const frame = page.frameLocator('iframe[title="Page preview"]')
const previewText = await frame
  .locator('h1')
  .first()
  .innerText()
  .catch(() => 'NO H1')
console.log('PREVIEW H1:', previewText)
await page
  .getByRole('button', { name: /^publish/i })
  .first()
  .click()
await page.waitForTimeout(400)
await page
  .getByRole('dialog')
  .getByRole('button', { name: /publish/i })
  .click()
await page.waitForTimeout(1500)
await page.screenshot({ path: `${out}/cms-4-published.png` })
await page.getByRole('link', { name: /back to storefront/i }).click()
await page.waitForURL((u) => u.pathname === '/')
await page.waitForTimeout(1200)
console.log('LIVE H1:', await page.locator('h1').first().innerText())
await page.screenshot({ path: `${out}/cms-5-live.png` })
// device switcher mobile
await page.goto(base + '/admin/editor?doc=page:home', { waitUntil: 'networkidle' })
await page.waitForTimeout(2000)
await page
  .getByRole('button', { name: /mobile|phone/i })
  .first()
  .click()
  .catch(() => {})
await page.waitForTimeout(1500)
await page.screenshot({ path: `${out}/cms-6-mobile-preview.png` })
await page.setViewportSize({ width: 390, height: 844 })
await page.reload({ waitUntil: 'networkidle' })
await page.waitForTimeout(2000)
await page.screenshot({ path: `${out}/cms-7-editor-390.png`, fullPage: true })
await page.waitForTimeout(1200)
await page.screenshot({ path: `${out}/cms-6-mobile-preview.png` })
await browser.close()
console.log(errors.length ? errors.join('\n') : 'NO ERRORS')
